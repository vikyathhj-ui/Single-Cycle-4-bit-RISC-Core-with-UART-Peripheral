#!/usr/bin/env python3
"""Build the boot ROM image (docs/SPEC.md §7) and write rtl/soc/bootrom_image.svh.

    python3 scripts/gen_bootrom.py [sw/boot/<file>.S]        (default: sw/boot/boot.S)

Assembles and links the source at address 0 with riscv64-unknown-elf-gcc
(-march=rv32i_zicsr_zbb -mabi=ilp32), extracts the binary and writes it as a SystemVerilog
include: `localparam int ROM_WORDS` and `localparam logic [31:0] ROM_IMAGE [64]` (unused words 0).
Fails if the image is larger than 256 bytes (64 words, MEMORY_MAP BOOTROM size).
"""
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
src = Path(sys.argv[1]) if len(sys.argv) > 1 else REPO / "sw" / "boot" / "boot.S"
words_max = 64
with tempfile.TemporaryDirectory() as d:
    elf, binf = Path(d) / "boot.elf", Path(d) / "boot.bin"
    subprocess.run(["riscv64-unknown-elf-gcc", "-march=rv32i_zicsr_zbb", "-mabi=ilp32", "-nostdlib",
                    "-nostartfiles", "-Wl,-Ttext=0x0", "-Wl,--no-relax", "-o", str(elf), str(src)], check=True)
    subprocess.run(["riscv64-unknown-elf-objcopy", "-O", "binary", "-j", ".text", str(elf), str(binf)], check=True)
    data = binf.read_bytes()
data += b"\0" * (-len(data) % 4)
n = len(data) // 4
if n > words_max:
    sys.exit(f"boot ROM image is {len(data)} bytes, more than {4 * words_max}")
words = [int.from_bytes(data[4 * i:4 * i + 4], "little") for i in range(n)] + [0] * (words_max - n)
rel = src.resolve().relative_to(REPO)
lines = [f"// Generated by scripts/gen_bootrom.py from {rel}. Do not edit.",
         f"localparam int ROM_WORDS = {n};",
         "localparam logic [31:0] ROM_IMAGE [64] = '{"]
lines += [f"    32'h{w:08x}{',' if i < words_max - 1 else ''}" for i, w in enumerate(words)]
lines += ["};", ""]
(REPO / "rtl" / "soc" / "bootrom_image.svh").write_text("\n".join(lines))
print(f"rtl/soc/bootrom_image.svh: {n} words ({len(data)} bytes) from {rel}")
