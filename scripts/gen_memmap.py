#!/usr/bin/env python3
"""Generate the memory-map views from scripts/memmap.yaml (single source; BRIEF A3, A7).

Outputs:
  docs/MEMORY_MAP.md       human-readable map (regions per memory configuration, every register)
  sw/include/lp_rv32.h     C header: region bases/sizes, register addresses, field masks, resets, enums
  tb/memmap.py             Python dicts for the cocotb testbenches

    python3 scripts/gen_memmap.py           # write all outputs
    python3 scripts/gen_memmap.py --check   # exit 1 if any output is stale (used by CI)

The PMU registers are imported from the YAML named by its `import:` key (P2's regmap.yaml).
"""

from __future__ import annotations

import argparse
import pprint
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "scripts" / "memmap.yaml"
BANNER = "Generated by scripts/gen_memmap.py from scripts/memmap.yaml. Do not edit."
APB_SLOT = 0x1000


def check_regs(name: str, regs: list[dict], width: int, enums: dict) -> None:
    """Validate one register list and annotate it with masks and reset values."""
    seen: set[int] = set()
    for r in regs:
        assert r["addr"] % 4 == 0 and r["addr"] < APB_SLOT, (name, r["name"], "address")
        assert r["addr"] not in seen, f"{name}: duplicate address {r['addr']:#x}"
        assert r["access"] in ("RO", "RW", "W1C", "WO"), (name, r["name"], r["access"])
        seen.add(r["addr"])
        used = 0
        r["reset"] = 0
        for f in r["fields"]:
            msb, lsb = f["bits"]
            assert width > msb >= lsb >= 0, (name, r["name"], f["name"])
            mask = ((1 << (msb - lsb + 1)) - 1) << lsb
            assert not used & mask, f"{name}.{r['name']}: overlapping fields"
            assert f["reset"] < (1 << (msb - lsb + 1)), (name, r["name"], f["name"], "reset too wide")
            if "enum" in f:
                assert f["enum"] in enums, (name, r["name"], f["name"], "unknown enum")
            used |= mask
            f["mask"] = mask
            r["reset"] |= f["reset"] << lsb
        r["mask"] = used


def load() -> dict:
    m = yaml.safe_load(SRC.read_text())
    m.setdefault("enums", {})
    configs = list(m["configs"])
    # Regions: aligned, inside 32 bits, no overlap in any configuration.
    for cfg in configs:
        spans = []
        for g in m["regions"]:
            size = g["size"][cfg]
            assert size > 0 and size & (size - 1) == 0, (g["name"], cfg, "size must be a power of 2")
            assert g["base"] % size == 0, (g["name"], cfg, "base not aligned to size")
            spans.append((g["base"], g["base"] + size, g["name"]))
        spans.sort()
        for (b0, e0, n0), (b1, _, n1) in zip(spans, spans[1:]):
            assert e0 <= b1, f"{cfg}: {n0} overlaps {n1}"
    apb = next(g for g in m["regions"] if g["name"] == "APB")
    bases = set()
    for p in m["peripherals"]:
        if "import" in p:
            src = yaml.safe_load((REPO / p["import"]).read_text())
            assert src["data_width"] == m["data_width"], (p["name"], "data width")
            assert (1 << src["addr_width"]) <= APB_SLOT, (p["name"], "does not fit one APB slot")
            p["registers"] = src["registers"]
            p["imported_enums"] = src.get("enums", {})
        enums = {**m["enums"], **p.get("imported_enums", {})}
        for en, vals in enums.items():  # YAML 1.1 reads bare ON/OFF/YES/NO as booleans
            assert all(isinstance(k, str) for k in vals), f"enum {en}: quote keys like 'ON'/'OFF'"
        p["enums"] = enums
        assert p["base"] % APB_SLOT == 0, (p["name"], "base")
        assert apb["base"] <= p["base"] < apb["base"] + apb["size"][configs[0]], (p["name"], "outside APB")
        assert p["base"] not in bases, (p["name"], "slot in use")
        bases.add(p["base"])
        check_regs(p["name"], p["registers"], m["data_width"], enums)
    irqs = [p["irq"] for p in m["peripherals"] if p.get("irq") is not None]
    assert len(irqs) == len(set(irqs)) and all(0 <= i < 8 for i in irqs), "IRQ numbers"
    return m


def bits(f: dict) -> str:
    msb, lsb = f["bits"]
    return f"[{msb}]" if msb == lsb else f"[{msb}:{lsb}]"


def first_sentence(text: str) -> str:
    return text.split(". ")[0].rstrip(".") + "."


def markdown(m: dict) -> str:
    cfgs = list(m["configs"])
    out = ["# Memory map", "", f"<!-- {BANNER} -->", "",
           "All addresses are byte addresses on the 32-bit core bus. Every number in this file comes from "
           "`scripts/memmap.yaml`. An access to an address that is not listed below gets an error response, "
           "which the core reports as an access fault (docs/SPEC.md §6.3).", "",
           "## Memory configurations", ""]
    for c, d in m["configs"].items():
        out.append(f"- **{c}**: {d}")
    out += ["", "## Regions", "",
            "| Region | Base | " + " | ".join(f"Size ({c})" for c in cfgs) + " | Ports | Access | Domain | Description |",
            "|---|---|" + "---|" * len(cfgs) + "---|---|---|---|"]
    for g in m["regions"]:
        sizes = " | ".join(f"{g['size'][c]} B" for c in cfgs)
        out.append(f"| {g['name']} | `{g['base']:#010x}` | {sizes} | {', '.join(g['ports'])} | "
                   f"{g['access']} | {g['domain']} | {g['desc']} |")
    out += ["", "## APB peripherals", "",
            "Each peripheral has one 4 KB slot. Accesses must be 32-bit and word-aligned. Access types:",
            "", "- **RO**: read-only; a write gets an error response and changes nothing.",
            "- **RW**: read/write.", "- **W1C**: write 1 to clear.", "- **WO**: write-only; reads return 0.",
            "", "Unlisted bits read 0, and writes to them are ignored.", "",
            "| Base | Peripheral | Domain | IRQC source | Description |", "|---|---|---|---|---|"]
    for p in m["peripherals"]:
        irq = "—" if p.get("irq") is None else str(p["irq"])
        out.append(f"| `{p['base']:#010x}` | [{p['name']}](#{p['name'].lower()}) | {p['domain']} | {irq} | "
                   f"{first_sentence(p['desc'].strip())} |")
    for p in m["peripherals"]:
        out += ["", f"## {p['name']}", "", p["desc"].strip(), ""]
        if "import" in p:
            out += [f"Registers imported from `{p['import']}`.", ""]
        out += ["| Address | Register | Access | Reset | Description |", "|---|---|---|---|---|"]
        for r in p["registers"]:
            out.append(f"| `{p['base'] + r['addr']:#010x}` | {p['name']}_{r['name']} | {r['access']} | "
                       f"`{r['reset']:#010x}` | {first_sentence(r['desc'].strip())} |")
        out += ["", "| Register | Bits | Field | Reset | Description |", "|---|---|---|---|---|"]
        for r in p["registers"]:
            for f in sorted(r["fields"], key=lambda f: -f["bits"][0]):
                enum = f" ({f['enum']} encoding)" if "enum" in f else ""
                out.append(f"| {r['name']} | {bits(f)} | {f['name']} | `{f['reset']:#x}` | "
                           f"{f['desc'].strip()}{enum} |")
        if p["enums"]:
            out.append("")
            for en, vals in p["enums"].items():
                out.append(f"**{en}**: " + ", ".join(f"{k} = {v}" for k, v in vals.items()))
                out.append("")
    return "\n".join(out).rstrip() + "\n"


def c_header(m: dict) -> str:
    g = "LP_RV32_H"
    out = [f"/* {BANNER} */", f"#ifndef {g}", f"#define {g}", "", "#include <stdint.h>", ""]
    for c in m["configs"]:
        out.append(f"/* Memory configuration {c}: {m['configs'][c]} */")
    out += ["#if !defined(LP_RV32_CFG_GDS) && !defined(LP_RV32_CFG_SIM)",
            "#error \"define LP_RV32_CFG_GDS or LP_RV32_CFG_SIM\"", "#endif", ""]
    for r in m["regions"]:
        out.append(f"#define {r['name']}_BASE 0x{r['base']:08x}u")
    for c in m["configs"]:
        out.append(f"#ifdef LP_RV32_CFG_{c}")
        for r in m["regions"]:
            out.append(f"#define {r['name']}_SIZE {r['size'][c]}u")
        out.append("#endif")
    out.append("")
    for p in m["peripherals"]:
        P = p["name"]
        out.append(f"/* {P} @ 0x{p['base']:08x} */")
        out.append(f"#define {P}_BASE 0x{p['base']:08x}u")
        if p.get("irq") is not None:
            out.append(f"#define {P}_IRQ {p['irq']}u")
        for en, vals in p["enums"].items():
            for k, v in vals.items():
                out.append(f"#define {P}_{en.upper()}_{k} {v}u")
        for r in p["registers"]:
            R = f"{P}_{r['name']}"
            out.append(f"#define {R}_OFFSET 0x{r['addr']:03x}u")
            out.append(f"#define {R} (*(volatile uint32_t *)({P}_BASE + {R}_OFFSET))")
            out.append(f"#define {R}_RESET 0x{r['reset']:08x}u")
            for f in r["fields"]:
                out.append(f"#define {R}_{f['name']}_SHIFT {f['bits'][1]}u")
                out.append(f"#define {R}_{f['name']}_MASK 0x{f['mask']:08x}u")
        out.append("")
    out += [f"#endif /* {g} */", ""]
    return "\n".join(out)


def python_module(m: dict) -> str:
    regions = {r["name"]: {"base": r["base"], "size": r["size"]} for r in m["regions"]}
    periph = {}
    for p in m["peripherals"]:
        periph[p["name"]] = {
            "base": p["base"], "irq": p.get("irq"), "enums": p["enums"],
            "regs": {r["name"]: {"addr": p["base"] + r["addr"], "access": r["access"], "reset": r["reset"],
                                 "mask": r["mask"],
                                 "fields": {f["name"]: (f["bits"][0], f["bits"][1]) for f in r["fields"]}}
                     for r in p["registers"]},
        }
    return "\n".join([f'"""{BANNER}"""', "",
                      f"CONFIGS = {pprint.pformat(list(m['configs']), width=110)}", "",
                      f"REGIONS = {pprint.pformat(regions, width=110, sort_dicts=False)}", "",
                      f"PERIPHERALS = {pprint.pformat(periph, width=110, sort_dicts=False)}", ""])


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if an output is stale")
    args = ap.parse_args()
    m = load()
    outputs = {REPO / "docs" / "MEMORY_MAP.md": markdown(m),
               REPO / "sw" / "include" / "lp_rv32.h": c_header(m),
               REPO / "tb" / "memmap.py": python_module(m)}
    stale = []
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(REPO))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(REPO)}")
    if stale:
        print("stale (run python3 scripts/gen_memmap.py):", *stale, sep="\n  ")
        return 1
    if args.check:
        print("memory map outputs are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
